def fixed_pages(p):
    pages = {a: cs for a, cs in p['source_pages'].items() if a.startswith('m209-') and (not a.startswith('m209-e1-')) and (a != 'm209-e10-p10')}
    for ce in (82, 144, 145, 166):
        pages['ce' + str(ce)] = p['source_pages']['ce' + str(ce)]
    pages['ce44'] = p['source_pages']['ce44']
    pages['ce45'] = p['source_pages']['ce45'][99:111] + [p['source_pages']['ce45'][142]]
    pages['ce7'] = p['source_pages']['ce7'][442:466]
    return pages

def page_index(a):
    return 10000 + int(a[2:]) if a.startswith('ce') else int(a.split('-')[1][1:]) * 100 + int(a.split('-')[2][1:])


def correction(raw, kind):
    # JSON comes from the user's lawful local projection, never from public source.
    value = json.loads(raw)
    text = json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(',', ':'))
    require(isinstance(value, dict) and all(k in value for k in ('objects', 'flows', 'cues', 'messages', 'sprites')), 'Incomplete G3 correction projection')
    if kind == 'doors':
        require(')g3doors"' not in text, 'Invalid door raw-string delimiter')
        return '// Generated by tools/g3_route_doors.py from fixed, verified source.\nconstexpr char area3DoorCorrection[] = R"g3doors(' + text + ')g3doors";\n'
    require(kind == 'cold' and ')g3cold"' not in text, 'Invalid cold raw-string delimiter')
    return '// Fixed offline CN source; generated by g3_access_cold_room.py.\nconstexpr char area3ColdRoomCorrection[] = R"g3cold(' + text + ')g3cold";\n'


def no_links(path):
    p = path.absolute()
    require(not any(v.is_symlink() for v in (p, *p.parents)), 'Symlink local input/output')


def generate(manifest_path, output):
    no_links(manifest_path)
    no_links(output)
    require(manifest_path.stat().st_size <= 65536, 'Oversized local input manifest')
    manifest = json.loads(manifest_path.read_bytes())
    contract = json.loads(Path(__file__).with_name('public-compile-contract.json').read_bytes())
    require(manifest.get('schema') == 'nobihaza.local-compile-inputs.v1' and set(manifest.get('inputs', {})) == set(contract['inputs']), 'Expected all seven explicit local inputs')
    lowerers = {'dekisugi': lower_dekisugi, 'dora': lower_dora, 'cash': lower_cash, 'warehouse': lower_warehouse, 'final': lower_final}
    payload = {}
    for kind, lock in contract['inputs'].items():
        entry = manifest['inputs'][kind]
        require(set(entry) == {'file', 'sha256'} and entry['sha256'] == lock['sha256'], 'Unknown local source digest: ' + kind)
        path = Path(entry['file'])
        if not path.is_absolute():
            path = manifest_path.parent / path
        no_links(path)
        require(path.is_file() and path.stat().st_size <= 128 * 1024 * 1024, 'Missing/oversized local source: ' + kind)
        raw = path.read_bytes()
        require(digest(raw) == lock['sha256'], 'Changed local source: ' + kind)
        text = lowerers[kind](raw) if kind in lowerers else correction(raw, kind)
        data = text.encode('utf-8')
        require(digest(data) == lock['output_sha256'], 'Lowered output differs from supported fixed contract: ' + kind)
        payload[lock['output']] = data
    if output.exists():
        require(output.is_dir(), 'Output is not a directory')
        for p in output.rglob('*'):
            require(not p.is_symlink(), 'Symlink generated output')
            name = p.relative_to(output).as_posix()
            if p.is_dir():
                require(any(n.startswith(name + '/') for n in payload), 'Unexpected generated directory')
            else:
                require(p.is_file() and name in payload and p.read_bytes() == payload[name], 'Changed, nonregular or extra generated output')
    else:
        output.mkdir(parents=True)
    # Validate every input/output first; a failed generation cannot replace prior files.
    for name, raw in payload.items():
        path = output / name
        path.parent.mkdir(parents=True, exist_ok=True)
        if path.exists():
            continue
        with tempfile.NamedTemporaryFile(dir=path.parent, delete=False) as stream:
            temporary = Path(stream.name)
            stream.write(raw)
        try:
            os.replace(temporary, path)
        finally:
            temporary.unlink(missing_ok=True)
    return len(payload)


def main():
    parser = argparse.ArgumentParser(description='Generate seven fixed compile includes from lawful local data, without the private preparation pipeline.')
    parser.add_argument('--inputs', required=True, type=Path)
    parser.add_argument('--output', required=True, type=Path)
    args = parser.parse_args()
    try:
        print(f'{generate(args.inputs, args.output)} local content includes verified/generated')
    except (ValueError, OSError, KeyError, TypeError, StopIteration) as error:
        parser.exit(1, f'Rejected local compile input: {error}\n')


if __name__ == '__main__':
    main()
